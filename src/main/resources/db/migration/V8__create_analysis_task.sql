CREATE TABLE analysis_task (
    id BIGINT NOT NULL AUTO_INCREMENT,
    track_file_id BIGINT NOT NULL,
    abnormal_threshold DOUBLE NOT NULL,
    status VARCHAR(16) NOT NULL,
    attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts INT UNSIGNED NOT NULL DEFAULT 3,
    analysis_result_id BIGINT NULL,
    error_message VARCHAR(500) NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    started_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_analysis_task PRIMARY KEY (id),
    CONSTRAINT fk_analysis_task_file FOREIGN KEY (track_file_id) REFERENCES track_file (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_analysis_task_result FOREIGN KEY (analysis_result_id) REFERENCES analysis_result (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_analysis_task_threshold CHECK (abnormal_threshold >= 0),
    CONSTRAINT chk_analysis_task_attempts CHECK (max_attempts > 0 AND attempt_count <= max_attempts),
    CONSTRAINT chk_analysis_task_status CHECK (status IN ('PENDING','RUNNING','SUCCESS','FAILED')),
    CONSTRAINT chk_analysis_task_result_state CHECK ((status = 'SUCCESS' AND analysis_result_id IS NOT NULL) OR (status <> 'SUCCESS' AND analysis_result_id IS NULL)),
    INDEX idx_analysis_task_file_created (track_file_id, created_at DESC, id DESC),
    INDEX idx_analysis_task_status_updated (status, updated_at, id)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
